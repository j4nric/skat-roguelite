/** The icon as one SVG path at (x0, y0), `u` units per icon pixel. */
export function glyph(kind: MapIcon, x0: number, y0: number, u = 1, colour?: string): string {
  const rows = GRID[kind];
  const d: string[] = [];
  const n = (v: number): string => String(Math.round(v * 100) / 100);
  rows.forEach((row, j) => {
    let i = 0;
    while (i < 16) {
      if (row[i] !== '#') {
        i += 1;
        continue;
      }
      let k = i;
      while (k < 16 && row[k] === '#') k += 1;
      d.push(`M${n(x0 + i * u)} ${n(y0 + j * u)}h${n((k - i) * u)}v${n(u)}h${n(-(k - i) * u)}z`);
      i = k;
    }
  });
  return `<path d="${d.join('')}" fill="${colour ?? ICON_COLOUR[kind]}"/>`;
}

/** The icon as a small inline SVG of `px` CSS pixels. */
export function mapIcon(kind: MapIcon, px: number, colour?: string, cls = ''): string {
  return `<svg class="map-icon ${cls}" viewBox="0 0 16 16" width="${px}" height="${px}" shape-rendering="crispEdges" aria-hidden="true">${glyph(kind, 0, 0, 1, colour)}</svg>`;
}
