// Card backs, a small registry of designs (a cosmetic display setting, no
// game logic). The default is "Distel": our own pixel drawing after the
// traditional Altenburger thistle back (ochre rim, dark blue frame, a cross
// band of black and white triangles, four panels of thistles, cornflower
// fans and golden scrolls on a cream ground, the lower panels mirrored).
// No external asset is used; see web/LICENSES.md.
//
// Each design comes in two sizes: the full picture and a simplified one for
// tiny backs (the opponents' fans, about 10 px wide), where fine detail would
// only turn into noise. Both are <symbol>s in the card sprite (./art.ts),
// in the card's 120 × 180 box. The drawings are in ./backsprite.ts, which
// only the build runs (web/sprite/plugin.ts); this module knows the ids.

/**
 * The available back designs. The player's edition shows the back of his
 * character (`back` in characters.ron, DESIGN 9.3): "distel" by default,
 * "shirker", "tailoress" and "heart_brother" for the characters of
 * 03.11.2026. Since ADR 0015 the opponents' cards show their own back
 * (`back` in guests.ron and bosses.ron): "regulars" for the Stammgäste,
 * one per boss. Every picture but the Distel is generated by
 * tools/cardart/backs.py into ./backs.gen.ts.
 */
export type BackDesign =
  | 'distel'
  | 'shirker'
  | 'tailoress'
  | 'heart_brother'
  | 'regulars'
  | 'black_peter'
  | 'grandma'
  | 'the_pusher'
  | 'ramscher'
  | 'twins'
  | 'the_old_man'
  | 'moon'
  | 'stars'
  | 'lantern';

/** Every design once (a record, so the compiler sees a missing one). */
const DESIGNS: Record<BackDesign, true> = {
  distel: true,
  shirker: true,
  tailoress: true,
  heart_brother: true,
  regulars: true,
  black_peter: true,
  grandma: true,
  the_pusher: true,
  ramscher: true,
  twins: true,
  the_old_man: true,
  moon: true,
  stars: true,
  lantern: true,
};

const KNOWN = new Set<string>(Object.keys(DESIGNS));

/** Older back ids (saves, content defaults) and the design they show now. */
const ALIASES: Record<string, BackDesign> = { opponent: 'regulars' };

/** The design of a back id from the core; unknown ids show the Stammgäste back. */
export function backDesign(id: string | null | undefined): BackDesign {
  if (!id) return DEFAULT_BACK;
  const known = ALIASES[id] ?? id;
  return KNOWN.has(known) ? (known as BackDesign) : 'regulars';
}

export const DEFAULT_BACK: BackDesign = 'distel';

let playerBack: BackDesign = DEFAULT_BACK;

/**
 * Set the back of the player's edition (the character's `back` from the
 * core); unknown or missing ids show the Distel. Presentation only.
 */
export function setPlayerBack(id: string | null | undefined): void {
  playerBack = id && KNOWN.has(id) ? (id as BackDesign) : DEFAULT_BACK;
}

/** The back the player's cards, the skat and the deck show now. */
export function currentPlayerBack(): BackDesign {
  return playerBack;
}

/** Size variant of a back: the full picture or the simplified one. */
export type BackSize = 'full' | 'small';

/** Symbol id of a back design in the sprite. */
export function backId(design: BackDesign = DEFAULT_BACK, size: BackSize = 'full'): string {
  return `bk-${design}${size === 'small' ? '-s' : ''}`;
}
