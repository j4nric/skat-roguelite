"""Emit the pixel deck as a TypeScript module for the web app.

    python3 tools/cardart/emit.py            # writes web/src/ui/pixelcards.gen.ts
    python3 tools/cardart/emit.py --check    # fails if the committed file is stale

Every face is its art grid (33 x 49 art pixels), one string per row. A
capital letter A-Z is a pixel of the corner index (its lowercase palette
key), "." is paper, any other key a picture pixel. The web app splits the
two layers so card modifications can lie between picture and index
(web/src/ui/art.ts). The "Untot" faces of all 32 cards (untot.py: zombie
pictures, rotten number cards) and the eight suit-independent faces of the
"Wandelkarte" (wild.py) follow in the same form; the frames, marks and
bands of the card modifications are drawn by web/src/ui/cards.ts after
fx3.py.
"""

import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import aces2  # noqa: E402
import cards2  # noqa: E402
import untot  # noqa: E402
import wild  # noqa: E402
from pix import BG, BIG, GH, GW, GLYPH, INK, PAL, SIGN, Grid  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'web', 'src', 'ui', 'pixelcards.gen.ts')

# Suit and rank codes of the web app (glossary: Clubs = Eichel, Spades =
# Gruen, Hearts = Rot, Diamonds = Schellen; J = Unter, Q = Oberin).
SUITS = {'C': 'Eichel', 'S': 'Gruen', 'H': 'Rot', 'D': 'Schellen'}
RANKS = {'7': 7, '8': 8, '9': 9, 'T': 10, 'J': 'U', 'Q': 'O', 'K': 'K', 'A': 'A'}


def face(suit, rank):
    if rank == 'A':
        return aces2.ACE[suit]()
    if rank in cards2.FIG:
        return cards2.FIG[rank](suit)
    return cards2.number(suit, rank)


def index_layer(suit, rank):
    g = Grid()
    g.index(str(rank), suit)
    return g.g


# Keys of the "Untot" zombie faces (untot.py) in the TypeScript grid: its
# capital letters become lowercase ones (capitals mean corner index there).
UNDEAD_KEYS = {'Z': 'z', 'X': 'x', 'E': 'e'}


def undead_face(suit, rank):
    """The Untot face of a card: the zombie picture of a picture card
    (without its skull marker), the rotten pips of a number card."""
    if isinstance(rank, int):
        return untot.zombie_number(suit, rank)[0]
    untot.ZOMBIE_GRID_MARKER = False
    try:
        g, _ = untot.zombie(suit, rank)
    finally:
        untot.ZOMBIE_GRID_MARKER = True
    return g


def undead_palette():
    pal = {UNDEAD_KEYS.get(k, k): v for k, v in untot.EXTRA.items() if k in UNDEAD_KEYS}
    pal.update(untot.ROT_PAL)
    return pal


def rows(suit, rank, grid=None):
    full = (grid if grid is not None else face(suit, rank)).g
    idx = index_layer(suit, rank)
    out = []
    for y in range(GH):
        line = ''
        for x in range(GW):
            c = full[y, x]
            if idx[y, x] != '.':
                # The index is stamped last, so it is what the board shows.
                assert c == idx[y, x], (suit, rank, x, y)
                c = c.upper()
            else:
                c = UNDEAD_KEYS.get(c, c)
            line += c
        out.append(line)
    return out


def ts():
    lines = [
        '// Generated by tools/cardart/emit.py from the "Pixelstil" deck. Do not edit;',
        '// change the generator and run it again (tools/cardart/README.md).',
        '//',
        f'// A face is {GW} x {GH} art pixels (the card is {GW} x {GH}.5, the last half',
        '// row stays paper), one string per row. Capitals A-Z: corner index (the',
        '// lowercase key), ".": paper, any other key: picture. Keys of ART_PALETTE.',
        '',
        f'export const ART_W = {GW};',
        f'export const ART_H = {GH};',
        f"export const ART_PAPER = '{BG}';",
        '',
        'export const ART_PALETTE: Record<string, string> = {',
    ]
    lines += [f"  {k}: '{v}'," for k, v in PAL.items()]
    lines += [f"  '{k}': '{v}'," if k.isdigit() else f"  {k}: '{v}'," for k, v in undead_palette().items()]
    lines += ['};', '', '/** The held suit signs (7 wide), also used as suit icons. */',
              'export const ART_SIGNS: Record<string, string[]> = {']
    for code, suit in SUITS.items():
        lines.append(f'  {code}: [' + ', '.join(f"'{r}'" for r in BIG[suit]) + '],')
    lines += ['};', '', '/** Ink key of the corner index per suit. */',
              'export const ART_INK: Record<string, string> = {']
    lines += [f"  {code}: '{INK[suit]}'," for code, suit in SUITS.items()]
    lines += ['};', '', '/** The pixel letters of the corner index by rank code ("x" is ink). */',
              'export const ART_GLYPHS: Record<string, string[]> = {']
    for rc, rank in RANKS.items():
        lines.append(f'  {rc}: [' + ', '.join(f"'{r}'" for r in GLYPH[str(rank)]) + '],')
    lines += ['};', '', '/** Faces by suit code and rank code, e.g. "CA" (Eichel-Daus), "HJ" (Rot-Unter). */',
              'export const ART_FACES: Record<string, string[]> = {']
    for code, suit in SUITS.items():
        for rc, rank in RANKS.items():
            lines.append(f'  {code}{rc}: [')
            lines += [f"    '{r}'," for r in rows(suit, rank)]
            lines.append('  ],')
    lines += ['};', '', '/** "Untot": the faces of all 32 cards (untot.py), same codes. */',
              'export const ART_UNDEAD: Record<string, string[]> = {']
    for code, suit in SUITS.items():
        for rc, rank in RANKS.items():
            lines.append(f'  {code}{rc}: [')
            lines += [f"    '{r}'," for r in rows(suit, rank, undead_face(suit, rank))]
            lines.append('  ],')
    lines += ['};', '', '/** "Wandelkarte": eight faces by rank code, the same for every suit (wild.py). */',
              'export const ART_WILD: Record<string, string[]> = {']
    for rc, rank in RANKS.items():
        lines.append(f'  {rc}: [')
        lines += [f"    '{r}'," for r in rows('Wild', rank, wild.card(rank))]
        lines.append('  ],')
    lines += ['};', '', '/** The Wandelkarte\'s rainbow sign: index size (3 wide) and held size (7 wide). */',
              'export const ART_WILD_SIGN: string[] = [' + ', '.join(f"'{r}'" for r in SIGN['Wild']) + '];',
              'export const ART_WILD_BIG: string[] = [' + ', '.join(f"'{r}'" for r in BIG['Wild']) + '];',
              f"export const ART_WILD_INK = '{INK['Wild']}';", '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = ts()
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as fh:
            if fh.read() != text:
                sys.exit(f'{OUT} is stale: run python3 tools/cardart/emit.py')
        print('up to date')
    else:
        with open(OUT, 'w', encoding='utf-8') as fh:
            fh.write(text)
        print(f'wrote {OUT}')
