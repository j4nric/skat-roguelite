"""Emit the pixel deck as a TypeScript module for the web app.

    python3 tools/cardart/emit.py            # writes web/src/ui/pixelcards.gen.ts
    python3 tools/cardart/emit.py --check    # fails if the committed file is stale

Every face is its art grid (33 x 49 art pixels), one string per row. A
lowercase letter is a picture pixel, an uppercase letter a pixel of the
corner index (same palette key), "." is paper. The web app splits the two
layers so card modifications can lie between picture and index
(web/src/ui/art.ts).
"""

import os
import sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import aces2  # noqa: E402
import cards2  # noqa: E402
from pix import BG, BIG, GH, GW, GLYPH, INK, PAL, Grid  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'web', 'src', 'ui', 'pixelcards.gen.ts')

# Suit and rank codes of the web app (glossary: Clubs = Eichel, Spades =
# Gruen, Hearts = Rot, Diamonds = Schellen; J = Unter, Q = Oberin).
SUITS = {'C': 'Eichel', 'S': 'Gruen', 'H': 'Rot', 'D': 'Schellen'}
RANKS = {'7': 7, '8': 8, '9': 9, 'T': 10, 'J': 'U', 'Q': 'O', 'K': 'K', 'A': 'A'}


def face(suit, rank):
    if rank == 'A':
        return aces2.ACE[suit]()
    if rank in cards2.FIG:
        return cards2.FIG[rank](suit)
    return cards2.number(suit, rank)


def index_layer(suit, rank):
    g = Grid()
    g.index(str(rank), suit)
    return g.g


def rows(suit, rank):
    full = face(suit, rank).g
    idx = index_layer(suit, rank)
    out = []
    for y in range(GH):
        line = ''
        for x in range(GW):
            c = full[y, x]
            if idx[y, x] != '.':
                # The index is stamped last, so it is what the board shows.
                assert c == idx[y, x], (suit, rank, x, y)
                c = c.upper()
            line += c
        out.append(line)
    return out


def ts():
    lines = [
        '// Generated by tools/cardart/emit.py from the "Pixelstil" deck. Do not edit;',
        '// change the generator and run it again (tools/cardart/README.md).',
        '//',
        f'// A face is {GW} x {GH} art pixels (the card is {GW} x {GH}.5, the last half',
        '// row stays paper), one string per row. Lowercase: picture, uppercase: corner',
        '// index, ".": paper. Letters are keys of ART_PALETTE.',
        '',
        f'export const ART_W = {GW};',
        f'export const ART_H = {GH};',
        f"export const ART_PAPER = '{BG}';",
        '',
        'export const ART_PALETTE: Record<string, string> = {',
    ]
    lines += [f"  {k}: '{v}'," for k, v in PAL.items()]
    lines += ['};', '', '/** The held suit signs (7 wide), also used as suit icons. */',
              'export const ART_SIGNS: Record<string, string[]> = {']
    for code, suit in SUITS.items():
        lines.append(f'  {code}: [' + ', '.join(f"'{r}'" for r in BIG[suit]) + '],')
    lines += ['};', '', '/** Ink key of the corner index per suit. */',
              'export const ART_INK: Record<string, string> = {']
    lines += [f"  {code}: '{INK[suit]}'," for code, suit in SUITS.items()]
    lines += ['};', '', '/** The pixel letters of the corner index by rank code ("x" is ink). */',
              'export const ART_GLYPHS: Record<string, string[]> = {']
    for rc, rank in RANKS.items():
        lines.append(f'  {rc}: [' + ', '.join(f"'{r}'" for r in GLYPH[str(rank)]) + '],')
    lines += ['};', '', '/** Faces by suit code and rank code, e.g. "CA" (Eichel-Daus), "HJ" (Rot-Unter). */',
              'export const ART_FACES: Record<string, string[]> = {']
    for code, suit in SUITS.items():
        for rc, rank in RANKS.items():
            lines.append(f'  {code}{rc}: [')
            lines += [f"    '{r}'," for r in rows(suit, rank)]
            lines.append('  ],')
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = ts()
    if '--check' in sys.argv:
        with open(OUT, encoding='utf-8') as fh:
            if fh.read() != text:
                sys.exit(f'{OUT} is stale: run python3 tools/cardart/emit.py')
        print('up to date')
    else:
        with open(OUT, 'w', encoding='utf-8') as fh:
            fh.write(text)
        print(f'wrote {OUT}')
